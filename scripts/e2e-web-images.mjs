import assert from 'node:assert/strict'
import {launchBrowser} from './e2e-browser.mjs'
import {seedAndBoot,msg} from './e2e-fixture.mjs'
const browser=await launchBrowser()
try {
 const page=await browser.newPage({viewport:{width:1280,height:900}}),requests=[],errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.route('https://api.firecrawl.dev/v2/search',async route=>{
  const body=route.request().postDataJSON();requests.push(body)
  assert.equal(body.limit,3);assert.deepEqual(body.sources,['images'])
  const retryingPlant=body.query==='plant cell'&&requests.filter(request=>request.query==='plant cell').length>1
  const images=retryingPlant?['retried.svg']:body.query==='neuron diagram'||body.query==='plant cell'
    ? ['broken.svg','broken-second.svg',body.query==='plant cell'?'broken-third.svg':'third.svg']
    : ['figure.svg','backup.svg','third.svg']
  await route.fulfill({json:{success:true,data:{images:images.map((name,i)=>({imageUrl:body.query==='animal cell'&&i===0?'javascript:invalid':'https://image.example/'+name,url:'https://source.example/lesson-'+i,title:'图示'}))},creditsUsed:2}})
 })
 await page.route('https://image.example/**',route=>route.request().url().includes('/broken')?route.fulfill({status:404,body:''}):route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="600" height="320"><rect width="600" height="320" fill="#b8d6fa"/><text x="80" y="160" font-size="32">Learning diagram</text></svg>'}))
 const fence=(lang,spec)=>'```'+lang+'\n'+JSON.stringify(spec)+'\n```'
 const answer=fence('genui',{title:'简洁入口',items:[{type:'card',title:'无需 schema',items:[{type:'text',content:'结构正常'},{type:'image',query:'neuron diagram'}]}]})+'\n'+fence('web-image',{type:'image',query:'neuron diagram'})+'\n'+fence('web-image',{type:'image-group',items:[{query:'animal cell'},{query:'plant cell'}]})
 await seedAndBoot(page,{convs:[{id:'images',title:'图片测试',createdAt:1,updatedAt:1,messages:[msg('answer','assistant',answer)]}],settings:{lastConversationId:'images',appearance:'dark',apiKey:'chat-test',model:'deepseek-flash',firecrawlWebSearchEnabled:'false'}})
 await page.getByText('结构正常',{exact:true}).waitFor()
 assert.equal(requests.length,0)
 await page.getByRole('button',{name:'设置',exact:true}).click()
 const panel=page.getByTestId('firecrawl-settings')
 await panel.getByLabel('Firecrawl API Key').fill('fc-test')
 await page.getByRole('button',{name:'保存 API 设置',exact:true}).click()
 await panel.getByText('已保存，单图与双图配图能力已开启').waitFor()
 await panel.screenshot({path:'tmp/firecrawl-settings-desktop.png'})
 await page.setViewportSize({width:390,height:844})
 await panel.screenshot({path:'tmp/firecrawl-settings-mobile.png'})
 assert.ok(await panel.evaluate(el=>el.scrollWidth<=el.clientWidth))
 await page.setViewportSize({width:1280,height:900})
 await page.keyboard.press('Escape')
 await page.waitForFunction(()=>document.querySelectorAll('.reader-web-image img').length===3 && [...document.querySelectorAll('.reader-web-image img')].every(i=>i.naturalWidth>0)).catch(async e=>{console.log({requests,errors,body:(await page.locator('body').innerText()).slice(-5000)});throw e})
 assert.equal(requests.length,3)
 await page.getByRole('img',{name:'图片加载失败',exact:true}).waitFor()
 assert.ok((await page.locator('.reader-web-image-failed').boundingBox()).height<80,'three failures leave a compact broken-image placeholder')
 assert.equal(await page.locator('.reader-web-image img[src$="third.svg"]').count(),2,'failed first image swaps to cached third without another search')
 assert.equal(await page.locator('[data-reader-card] .reader-web-image img').count(),1)
 assert.equal(await page.locator('.reader-web-image img[src$="backup.svg"]').count(),1,'an invalid first candidate falls through to the second')
 await page.screenshot({path:'tmp/web-images-card.png'})
 await page.reload({waitUntil:'networkidle'})
 await page.waitForFunction(()=>document.querySelectorAll('.reader-web-image img').length===3)
 assert.equal(requests.length,3,'reload reuses selected references')
 await page.setViewportSize({width:390,height:844})
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
 assert.equal(await page.locator('.reader-web-images-pair').evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length),1)
 await page.screenshot({path:'tmp/web-images-mobile.png'})
 await page.setViewportSize({width:1280,height:900})
 let captured
 await page.route('**/chat/completions',async route=>{captured=route.request().postDataJSON();await route.fulfill({json:{choices:[{message:{content:fence('genui',{items:[{type:'card',title:'新请求图片',items:[{type:'image',query:'neuron diagram'}]}]})},finish_reason:'stop'}]}})})
 await page.getByRole('textbox',{name:'输入消息',exact:true}).fill('现在请直接在卡片里搜索一张神经元图片')
 await page.getByTestId('composer-send-stop').click()
 await page.getByText('新请求图片',{exact:true}).waitFor()
 const sent=JSON.stringify(captured.messages)
 assert.ok(sent.includes('当前阅读器运行时能力：Firecrawl 已配置'))
 assert.ok(sent.includes('image: query*:string'))
 assert.ok(sent.includes('image-group: items*:'))
 assert.ok(!sent.includes('fc-test'))
 assert.equal(requests.length,3,'new response reuses existing query')
 await page.getByRole('button',{name:'重试搜索',exact:true}).click()
 await page.locator('.reader-web-image img[src$="retried.svg"]').waitFor()
 assert.equal(requests.filter(request=>request.query==='plant cell').length,2,'retry makes a fresh Firecrawl request and displays its result')
 await page.getByRole('button',{name:'设置',exact:true}).click()
 await panel.getByRole('button',{name:'清除',exact:true}).click()
 await panel.getByText('修改尚未保存').waitFor()
 await panel.getByRole('button',{name:'保存 Firecrawl 配置',exact:true}).click()
 await panel.getByText('已清除，模型配图能力已关闭').waitFor()
 await page.keyboard.press('Escape')
 assert.equal(await page.locator('.reader-web-images').count(),0)
 assert.deepEqual(errors,[])
 console.log('PASS schema-free GenUI, key save/clear, single/dual images, persistent reuse and mobile layout')
}finally{await browser.close()}
