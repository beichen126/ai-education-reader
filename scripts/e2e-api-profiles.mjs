import assert from 'node:assert/strict'
import {launchBrowser} from './e2e-browser.mjs'
import {seedAndBoot} from './e2e-fixture.mjs'
import {openSettings} from './e2e-navigation.mjs'
const browser=await launchBrowser()
try {
 const page=await browser.newPage({viewport:{width:1100,height:850}})
 await seedAndBoot(page,{settings:{apiKey:'deepseek-key',model:'deepseek-flash'}})
 await openSettings(page,'api')
 const profile=page.getByTestId('api-profiles'),name=profile.getByLabel('配置名称'),key=page.getByPlaceholder('sk-...'),model=page.getByPlaceholder('deepseek-flash',{exact:true}),select=profile.getByLabel('当前使用的配置')
 await profile.getByRole('button',{name:'为当前配置命名',exact:true}).click()
 await name.fill('DeepSeek 官方');await profile.getByRole('button',{name:'保存名称',exact:true}).click()
 await select.locator('option:checked').filter({hasText:'DeepSeek 官方'}).waitFor({state:'attached'})
 await profile.getByRole('button',{name:'添加配置',exact:true}).click()
 await name.fill('TeamoRouter');await profile.getByLabel('新配置服务类型').selectOption('teamo')
 assert.equal(await profile.getByLabel('新配置 API Key').inputValue(),'')
 assert.equal(await profile.getByLabel('新配置服务地址').inputValue(),'https://api.teamorouter.com/v1')
 await profile.getByRole('button',{name:'保存并启用'}).click()
 await profile.getByRole('alert').filter({hasText:'填写 API Key'}).waitFor()
 await profile.getByLabel('新配置 API Key').fill('router-key');await profile.getByLabel('新配置模型').fill('custom-model')
 await profile.getByRole('button',{name:'保存并启用'}).click()
 await page.waitForFunction(()=>document.querySelector('input[placeholder="sk-..."]')?.value==='router-key')
 await model.fill('unsaved-model');await select.selectOption({label:'DeepSeek 官方'})
 await profile.getByRole('button',{name:'取消',exact:true}).click();assert.equal(await model.inputValue(),'unsaved-model')
 await select.selectOption({label:'DeepSeek 官方'});await profile.getByRole('button',{name:'保存并继续'}).click()
 await page.waitForFunction(()=>document.querySelector('input[placeholder="sk-..."]')?.value==='deepseek-key')
 await select.selectOption({label:'TeamoRouter'})
 await page.waitForFunction(()=>document.querySelector('input[placeholder="sk-..."]')?.value==='router-key')
 assert.equal(await model.inputValue(),'unsaved-model')
 await model.fill('discard-me');await select.selectOption({label:'DeepSeek 官方'});await profile.getByRole('button',{name:'放弃修改并继续'}).click()
 await page.waitForFunction(()=>document.querySelector('input[placeholder="sk-..."]')?.value==='deepseek-key')
 await select.selectOption({label:'TeamoRouter'});await page.waitForFunction(()=>document.querySelector('input[placeholder="sk-..."]')?.value==='router-key')
 assert.equal(await model.inputValue(),'unsaved-model')
 await profile.getByRole('button',{name:'重命名',exact:true}).click();await name.fill('我的中转');await profile.getByRole('button',{name:'保存名称'}).click()
 await page.reload({waitUntil:'networkidle'});await openSettings(page,'api')
 assert.equal(await key.inputValue(),'router-key');assert.equal(await select.locator('option:checked').textContent(),'我的中转')
 await page.setViewportSize({width:390,height:844})
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
 await page.screenshot({path:'tmp/api-profiles-mobile.png',fullPage:true})
 console.log('PASS named API profiles: explicit create, isolated credentials, cancel/save/discard switching, rename, persistence and mobile')
} finally {await browser.close()}
