import assert from 'node:assert/strict'
import { launchBrowser } from './e2e-browser.mjs'
import { seedAndBoot } from './e2e-fixture.mjs'
import { openDocumentLibrary } from './e2e-navigation.mjs'
const browser = await launchBrowser()
try {
  for (const [language, width] of [['zh-CN',390],['en',320]]) {
    const context = await browser.newContext({viewport:{width,height:740}})
    const page = await context.newPage(), errors = []
    page.setDefaultTimeout(45000)
    page.on('pageerror', error => errors.push(error.message))
    await seedAndBoot(page,{settings:{uiLanguage:language}})
    await openDocumentLibrary(page)
    await page.locator('[data-testid="document-library"] input[type="file"]').setInputFiles('test/fixtures/no-outline.pdf')
    await page.locator('[data-testid="reader-page-img"]').waitFor({state:'visible'})
    await page.evaluate(() => { window.__dshMockAiToc = req => req.phase === 'structure' ? JSON.stringify({levels:Array(936).fill(1)}) : JSON.stringify({rows:Array.from({length:936},(_, i)=>({title:'Entry '+i,pageLabel:'1',sourceImageIndex:1}))}) })
    if (await page.locator('[data-testid="reader-toc-toggle"]').getAttribute('aria-expanded') !== 'true') await page.locator('[data-testid="reader-toc-toggle"]').click()
    await page.locator('[data-testid="reader-toc-ai"]').click()
    await page.locator('[data-testid="toc-thumb-1"]').click()
    await page.locator('[data-testid="toc-picker-start"]').click()
    await page.locator('[data-testid="toc-review-edit-0"]').click()
    await page.locator('[data-testid="toc-review-page"]').fill('1')
    await page.locator('[data-testid="toc-review-calibrate"]').click()
    await page.locator('[data-testid="toc-review-edit-all"]').click()
    await page.locator('[data-testid="cb-save"]').click()
    await page.locator('[data-testid="chapter-builder"]').waitFor({state:'hidden'})
    const openEditor = async () => {
      if (await page.locator('[data-testid="reader-toc-toggle"]').getAttribute('aria-expanded') !== 'true') await page.locator('[data-testid="reader-toc-toggle"]').click()
      await page.locator('[data-testid="reader-toc-edit"]').click()
      await page.locator('[data-testid="cb-row"]').first().waitFor({state:'visible'})
    }
    await openEditor()
    const geometry = await page.locator('[data-testid="cb-row"]').evaluateAll(rows => rows.slice(0,4).map(row => {
      const bounds = row.getBoundingClientRect()
      const buttons = [...row.querySelectorAll('button')].map(button => button.getBoundingClientRect())
      return {top:bounds.top,bottom:bounds.bottom,contained:buttons.every(b=>b.top>=bounds.top&&b.bottom<=bounds.bottom&&b.left>=bounds.left&&b.right<=bounds.right)}
    }))
    assert.ok(geometry.every((row,i)=>row.contained&&(!i||row.top>=geometry[i-1].bottom)), '936 rows do not shrink or overlap; arrows stay inside their own row')
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
    await page.locator('[data-testid="cb-select-all"]').click()
    await page.locator('[data-testid="cb-bulk-delete"]').click()
    assert.match(await page.locator('[data-testid="cb-bulk-delete-confirm"]').textContent(), /936/)
    await page.locator('[data-testid="cb-bulk-delete-no"]').click()
    assert.equal(await page.locator('[data-testid="cb-row"]').count(),936)
    await page.locator('[data-testid="cb-clear-selection"]').click()
    for (const i of [0,1]) await page.locator('[data-testid="cb-select-'+i+'"]').check()
    await page.locator('[data-testid="cb-bulk-delete"]').click()
    await page.locator('[data-testid="cb-bulk-delete-yes"]').click()
    assert.equal(await page.locator('[data-testid="cb-row"]').count(),934)
    await page.locator('[data-testid="cb-title-0"]').fill('Edited after deletion')
    await page.locator('[data-testid="cb-undo-delete"]').click()
    assert.equal(await page.locator('[data-testid="cb-row"]').count(),936)
    assert.equal(await page.locator('[data-testid="cb-title-2"]').inputValue(),'Edited after deletion')
    for (const i of [0,1]) await page.locator('[data-testid="cb-select-'+i+'"]').check()
    await page.locator('[data-testid="cb-bulk-delete"]').click()
    await page.locator('[data-testid="cb-bulk-delete-yes"]').click()
    await page.locator('[data-testid="cb-save"]').click()
    await page.locator('[data-testid="chapter-builder"]').waitFor({state:'hidden'})
    const readDoc = () => page.evaluate(()=>new Promise((resolve,reject)=>{
      const req=indexedDB.open('ai-education-reader')
      req.onsuccess=()=>{const db=req.result,get=db.transaction('documents').objectStore('documents').getAll();get.onsuccess=()=>{resolve(get.result[0]);db.close()};get.onerror=()=>reject(get.error)}
      req.onerror=()=>reject(req.error)
    }))
    let doc = await readDoc()
    assert.equal(doc.chapters.length,934)
    assert.equal(doc.chapterVersions.length,2)
    assert.equal(doc.chapterVersions[0].chapters.length,936)
    await openEditor()
    await page.locator('[data-testid="cb-versions"]').selectOption(doc.chapterVersions[0].id)
    await page.locator('[data-testid="cb-restore-version"]').click()
    await page.locator('[data-testid="cb-version-yes"]').click()
    assert.equal(await page.locator('[data-testid="cb-row"]').count(),936)
    assert.equal((await readDoc()).chapters.length,934,'loading a version is draft-only until Save')
    await page.locator('[data-testid="cb-save"]').click()
    await page.locator('[data-testid="chapter-builder"]').waitFor({state:'hidden'})
    await page.reload({waitUntil:'networkidle'})
    doc = await readDoc()
    assert.equal(doc.chapters.length,936)
    assert.equal(doc.chapterVersions.length,3,'restoration preserves old versions after reload')
    assert.deepEqual(errors,[])
    console.log('PASS '+language+'/'+width+'px: 936-row non-overlap, confirmed bulk deletion/cancel/undo preserving edits, local save, version restore and reload')
    await context.close()
  }
} finally { await browser.close() }
