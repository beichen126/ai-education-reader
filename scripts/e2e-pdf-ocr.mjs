import assert from 'node:assert/strict'
import {launchBrowser} from './e2e-browser.mjs'
import {seedAndBoot} from './e2e-fixture.mjs'
const browser=await launchBrowser()
try {
 const page=await browser.newPage({viewport:{width:1100,height:850}}), requests=[],errors=[]
 await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
 page.on('pageerror',e=>errors.push(e.message))
 let ocrCalls=0
 await page.route('https://api.deepseek.com/v1/tools/ocr',async route=>{
  assert.equal(route.request().headers().authorization,'Bearer ds-ocr-test')
  ocrCalls++
  await route.fulfill({json:{object:'ocr.result',page_count:1,pages:[{index:0,text:'OCR lesson page '+ocrCalls,finish_reason:'stop'}]}})
 })
 await page.route('**/chat/completions',async route=>{
  requests.push(route.request().postDataJSON())
  assert.equal(route.request().headers().authorization,'Bearer other-key')
  await route.fulfill({contentType:'text/event-stream',body:'data: '+JSON.stringify({choices:[{delta:{content:'已读取 OCR 文本。'},finish_reason:'stop'}]})+'\n\ndata: [DONE]\n\n'})
 })
 await seedAndBoot(page,{convs:[{id:'ocr-chat',title:'OCR test',messages:[],createdAt:1,updatedAt:1}],settings:{lastConversationId:'ocr-chat',apiBaseUrl:'https://other.example/v1',apiKey:'other-key',model:'text-model',visionCapability:'text-only',apiProfiles:JSON.stringify([{id:'ds',name:'DS OCR',config:{apiBaseUrl:'https://api.deepseek.com',apiKey:'ds-ocr-test',model:'deepseek-flash',visionCapability:'auto'}}])}})
 await page.locator('[data-testid="sidebar-entry-files"], [data-testid="rail-files"]').first().click()
 await page.locator('[data-testid="document-library"] input[type="file"]').setInputFiles('test/fixtures/outline-sample.pdf')
 await page.locator('[data-testid="document-reader"]').waitFor()
 await page.getByTestId('reader-page').click()
 const viewer = page.getByRole('dialog', {name:'PDF 页面查看',exact:true})
 await viewer.getByTestId('pdf-page-ocr').click()
 await page.getByLabel('OCR 结果',{exact:true}).waitFor()
 assert.equal(await page.getByLabel('OCR 结果',{exact:true}).inputValue(),'OCR lesson page 1')
 await page.getByRole('dialog').filter({has:page.getByLabel('OCR 结果',{exact:true})}).getByRole('button',{name:'关闭',exact:true}).click()
 await viewer.getByRole('button',{name:'关闭',exact:true}).click()
 await page.locator('[data-testid="reader-ctx-toggle"]').click()
 await page.getByLabel('PDF 发送方式',{exact:true}).selectOption('ocr')
 await page.locator('[data-testid="reader-ctx-current-page"]').click()
 await page.locator('[data-testid="reader-ctx-back"]').click()
 assert.equal(ocrCalls,1)
 const composer=page.getByRole('textbox',{name:'输入消息',exact:true})
 assert.equal(await composer.inputValue(),'')
 await composer.fill('总结这一页')
 await page.locator('[data-testid="composer-send-stop"]').click()
 await page.getByText('已读取 OCR 文本。',{exact:true}).first().waitFor()
 assert.equal(requests.length,1)
 assert.match(JSON.stringify(requests[0]),/OCR lesson page 1/)
 assert.doesNotMatch(JSON.stringify(requests[0]),/image_url|data:image/)
 await page.getByRole('button',{name:'预览页面',exact:true}).click()
 const img=page.locator('[data-testid="pdf-group-card"] img').first()
 await img.waitFor()
 await page.waitForFunction(()=>[...document.querySelectorAll('[data-testid="pdf-group-card"] img')].some(i=>i.naturalWidth>0))
 await page.locator('[data-testid="sidebar-entry-images"], [data-testid="rail-images"]').first().click()
 await page.getByTestId('gallery-thumbnail').first().click()
 const galleryViewer = page.getByRole('dialog', {name:'图片大图查看',exact:true})
 const cachedButton = galleryViewer.getByRole('button', {name:'查看 OCR',exact:true})
 await cachedButton.waitFor()
 const closeButton = galleryViewer.getByRole('button', {name:'关闭',exact:true})
 const [ocrBox, closeBox] = await Promise.all([cachedButton.boundingBox(), closeButton.boundingBox()])
 assert.ok(ocrBox && closeBox && ocrBox.x + ocrBox.width <= closeBox.x && Math.abs(ocrBox.y - closeBox.y) < 1)
 if (process.env.READER_VISUAL_DIR) await page.screenshot({ path: process.env.READER_VISUAL_DIR + '/viewer-ocr.png' })
 await cachedButton.click()
 assert.equal(await page.getByLabel('OCR 结果',{exact:true}).inputValue(),'OCR lesson page 1')
 await page.getByRole('button',{name:'复制 OCR 文本',exact:true}).click()
 await page.getByRole('button',{name:'已复制',exact:true}).waitFor()
 assert.equal(await page.evaluate(() => navigator.clipboard.readText()),'OCR lesson page 1')
 assert.equal(ocrCalls,1,'opening gallery OCR uses the matching PDF page cache')
 await page.keyboard.press('Escape')
 await page.getByLabel('OCR 结果',{exact:true}).waitFor({ state:'hidden' })
 await galleryViewer.waitFor({ state:'visible' })
 await closeButton.click()
 // Reload and add exactly the same page again: persistent cache, not merely in-memory dedup.
 await page.reload({waitUntil:'networkidle'})
 await page.locator('[data-testid="sidebar-entry-files"], [data-testid="rail-files"]').first().click()
 await page.locator('[data-testid^="doc-open-"]').first().click()
 await page.locator('[data-testid="reader-ctx-toggle"]').click()
 await page.getByLabel('PDF 发送方式',{exact:true}).selectOption('ocr')
 await page.locator('[data-testid="reader-ctx-current-page"]').click()
 await page.locator('[data-testid="reader-ctx-back"]').click()
 assert.equal(ocrCalls,1)
 await page.setViewportSize({width:390,height:844})
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
 await page.screenshot({path:'tmp/pdf-ocr-mobile.png'})
 await page.setViewportSize({width:1100,height:850})
 await seedAndBoot(page,{convs:[{id:'image-chat',title:'Image test',messages:[],createdAt:1,updatedAt:1}],settings:{lastConversationId:'image-chat',apiBaseUrl:'https://other.example/v1',apiKey:'other-key',model:'vision-model',visionCapability:'supports-image'}})
 await page.locator('[data-testid="sidebar-entry-files"], [data-testid="rail-files"]').first().click()
 await page.locator('[data-testid^="doc-open-"]').first().click()
 await page.locator('[data-testid="reader-ctx-toggle"]').click()
 await page.getByLabel('PDF 发送方式',{exact:true}).selectOption('image')
 await page.locator('[data-testid="reader-ctx-current-page"]').click()
 await page.locator('[data-testid="reader-ctx-back"]').click()
 await page.getByRole('textbox',{name:'输入消息',exact:true}).fill('看图片')
 await page.locator('[data-testid="composer-send-stop"]').click()
 await page.getByText('已读取 OCR 文本。',{exact:true}).first().waitFor()
 assert.equal(ocrCalls,1)
 assert.match(JSON.stringify(requests.at(-1)),/image_url/)
 assert.doesNotMatch(JSON.stringify(requests.at(-1)),/OCR lesson page/)
 assert.deepEqual(errors,[])
 console.log('PASS PDF page OCR preview, original image preview, text-only model request, unchanged composer, credential separation, persistent reuse and mobile layout')
} finally {await browser.close()}
