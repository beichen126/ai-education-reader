import { launchBrowser } from './e2e-browser.mjs'
import { openDocumentLibrary } from './e2e-navigation.mjs'

const BASE = process.env.E2E_BASE || 'http://localhost:5299/ai-education-reader/'
const PDF = 'test/fixtures/outline-sample.pdf'
const results = []
const errors = []
const assert = (condition, message) => results.push((condition ? 'PASS  ' : 'FAIL  ') + message)
const browser = await launchBrowser()
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const page = await context.newPage()
page.on('pageerror', error => errors.push('pageerror: ' + error.message))
page.on('dialog', dialog => { void dialog.accept() })

await page.goto(BASE, { waitUntil: 'networkidle' })
await page.locator('input[type="file"][accept*="image/"]').waitFor({ state: 'attached', timeout: 25000 })
await openDocumentLibrary(page)
await page.locator('[data-testid="document-library"] input[type="file"]').setInputFiles(PDF)
await page.locator('[data-testid="document-reader"]').waitFor({ state: 'visible', timeout: 40000 })
await page.locator('[data-testid="reader-page-img"]').waitFor({ state: 'visible', timeout: 30000 })
const reader = page.locator('[data-testid="document-reader"]')
const toc = page.locator('[data-testid="reader-toc"]')
const tocToggle = page.locator('[data-testid="reader-toc-toggle"]')
const pageBeforeToc = await page.locator('[data-testid="reader-page-input"]').inputValue()
const titleBeforeToc = await page.locator('[data-testid="reader-title"]').textContent()
const desktopBack = page.locator('[data-testid="reader-toc-back"]')
assert(await desktopBack.isVisible(), 'desktop TOC exposes a visible 返回阅读 action')
assert(await toc.getAttribute('id') === 'reader-toc-panel', 'TOC panel has the stable reader-toc-panel id')
assert(await tocToggle.getAttribute('aria-controls') === 'reader-toc-panel' && await tocToggle.getAttribute('aria-expanded') === 'true', 'desktop TOC toggle exposes expanded/controls state')
await desktopBack.click()
await toc.waitFor({ state: 'hidden', timeout: 5000 })
assert(await reader.count() === 1 && (await page.locator('[data-testid="reader-page-input"]').inputValue()) === pageBeforeToc && (await page.locator('[data-testid="reader-title"]').textContent()) === titleBeforeToc, 'desktop 返回阅读 closes only TOC and preserves Reader state')
assert(await tocToggle.getAttribute('aria-expanded') === 'false' && await tocToggle.evaluate((el) => el === document.activeElement), 'desktop 返回阅读 restores focus to reader-toc-toggle')
await tocToggle.click()
await toc.waitFor({ state: 'visible', timeout: 5000 })
assert(await tocToggle.getAttribute('aria-expanded') === 'true', 'desktop TOC can be reopened through reader-toc-toggle')
await desktopBack.click()
await toc.waitFor({ state: 'hidden', timeout: 5000 })
await page.setViewportSize({ width: 390, height: 844 })
await tocToggle.click()
await toc.waitFor({ state: 'visible', timeout: 5000 })
const tocBack = page.locator('[data-testid="reader-toc-back"]')
assert(await tocBack.count() === 1 && await tocBack.isVisible().catch(() => false), 'TOC drawer exposes a visible 返回阅读 action')
assert(await tocBack.getAttribute('aria-label').catch(() => null) === '返回 PDF 阅读', '返回阅读 has an accessible name')
assert(await tocToggle.getAttribute('aria-expanded') === 'true' && await tocToggle.getAttribute('aria-controls') === 'reader-toc-panel', 'mobile TOC toggle exposes expanded/controls state')
assert(await tocBack.evaluate((el) => el === document.activeElement), 'mobile TOC opening moves focus to 返回阅读')
await page.keyboard.press('Shift+Tab')
assert(await toc.evaluate((el) => el.contains(document.activeElement)), 'mobile TOC focus stays inside the overlay on reverse Tab')
if (await tocBack.count()) {
  await tocBack.click()
  await toc.waitFor({ state: 'hidden', timeout: 5000 })
  assert(await reader.count() === 1 && (await page.locator('[data-testid="reader-page-input"]').inputValue()) === pageBeforeToc && (await page.locator('[data-testid="reader-title"]').textContent()) === titleBeforeToc, '返回阅读 closes only the TOC drawer and keeps Reader state')
  await page.waitForFunction(() => document.activeElement?.getAttribute('data-testid') === 'reader-toc-toggle', null, { timeout: 5000 })
  assert(await tocToggle.getAttribute('aria-expanded') === 'false' && await tocToggle.evaluate((el) => el === document.activeElement), 'mobile 返回阅读 restores focus to reader-toc-toggle')
  await tocToggle.click()
  await toc.waitFor({ state: 'visible', timeout: 5000 })
  await page.keyboard.press('Escape')
  await toc.waitFor({ state: 'hidden', timeout: 5000 })
  assert(await reader.count() === 1 && await tocToggle.evaluate((el) => el === document.activeElement), 'mobile Escape closes TOC first and keeps Reader open')
}

await browser.close()
for (const line of results) console.log(line)
console.log('PAGEERRORS: ' + (errors.length ? errors.join(' | ') : '(none)'))
const passed = results.filter(line => line.startsWith('PASS')).length
console.log('SUMMARY ' + passed + '/' + results.length + ' passed')
process.exit(passed === results.length && errors.length === 0 ? 0 : 1)
