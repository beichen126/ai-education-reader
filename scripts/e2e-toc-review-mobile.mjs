import assert from 'node:assert/strict'
import { launchBrowser } from './e2e-browser.mjs'
import { seedAndBoot } from './e2e-fixture.mjs'
import { openDocumentLibrary } from './e2e-navigation.mjs'
const browser = await launchBrowser()
try {
  for (const [language, width] of [['zh-CN', 390], ['en', 320]]) {
    const context = await browser.newContext({ viewport: { width, height: 640 } })
    const page = await context.newPage(), errors = []
    page.on('pageerror', error => errors.push(error.message))
    await seedAndBoot(page, { settings: { uiLanguage: language } })
    await openDocumentLibrary(page)
    await page.locator('[data-testid="document-library"] input[type="file"]').setInputFiles('test/fixtures/no-outline.pdf')
    await page.locator('[data-testid="reader-page-img"]').waitFor({ state: 'visible', timeout: 30000 })
    const start = async count => {
      await page.evaluate(count => { window.__reviewCount = count; window.__dshMockAiToc = req => req.phase === 'structure' ? JSON.stringify({ levels: Array(window.__reviewCount).fill(1) }) : JSON.stringify({ rows: Array.from({ length: window.__reviewCount }, (_, i) => ({ title: 'Entry ' + i, pageLabel: i === 1 ? '' : String(Math.min(8, i + 1)), sourceImageIndex: 1 })) }) }, count)
      if (await page.locator('[data-testid="reader-toc-toggle"]').getAttribute('aria-expanded') !== 'true') await page.locator('[data-testid="reader-toc-toggle"]').click()
      await page.locator('[data-testid="reader-toc-ai"]').click()
      await page.locator('[data-testid="toc-thumb-7"]').click()
      await page.locator('[data-testid="toc-picker-start"]').click()
      await page.locator('[data-testid="toc-review-item-0"]').waitFor({ state: 'visible', timeout: 30000 })
    }
    await start(942)
    const list = page.locator('[data-testid="toc-review-list"]'), adjust = page.locator('[data-testid="toc-review-adjust"]')
    assert.equal(await page.locator('[data-testid="toc-review-issues"]').getAttribute('open'), null)
    assert.equal(await adjust.isVisible(), false)
    assert.ok((await list.boundingBox()).height >= 640 * .55, '942-row mobile review reserves the majority of height for the list')
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await page.locator('[data-testid="toc-review-edit-0"]').click()
    await page.locator('[data-testid="toc-review-page"]').fill('1')
    await page.locator('[data-testid="toc-review-calibrate"]').click()
    await page.locator('[data-testid="toc-review-ok-0"]').click()
    await page.locator('[data-testid="toc-review-edit-1"]').click()
    await page.locator('[data-testid="toc-review-level"]').fill('')
    await page.locator('[data-testid="toc-review-delete-1"]').click()
    assert.equal(await page.locator('[data-testid^="toc-review-item-"]').count(), 941)
    assert.match(await page.locator('[data-testid="toc-review-progress"]').textContent(), /1 \/ 941/)
    await page.locator('[data-testid="toc-review-title"]').fill('Edited after deletion')
    await page.locator('[data-testid="toc-review-undo-delete"]').click()
    await page.locator('[data-testid="toc-review-edit-1"]').click()
    assert.equal(await page.locator('[data-testid="toc-review-level"]').inputValue(), '')
    assert.ok((await page.locator('[data-testid="toc-review-item-2"]').textContent()).includes('Edited after deletion'))
    await page.locator('[data-testid="toc-review-delete-1"]').click()
    await page.locator('[data-testid="toc-review-preview"]').click()
    await page.locator('[data-testid="toc-review-preview-bar"]').waitFor({ state: 'visible' })
    assert.equal(await page.locator('[data-testid="reader-toc-toggle"]').getAttribute('aria-expanded'), 'false', 'PDF preview is not covered by the old mobile outline drawer')
    assert.equal(await list.isVisible(), false)
    assert.equal(await page.locator('[data-testid="reader-page-img"]').isVisible(), true)
    await page.locator('[data-testid="toc-review-return"]').click()
    assert.equal(await page.locator('[data-testid^="toc-review-item-"]').count(), 941)
    await page.locator('[data-testid="toc-review-collapse-edit"]').click()
    assert.equal(await adjust.isVisible(), false)
    await page.locator('[data-testid="toc-review-close"]').click()
    await start(3)
    await page.locator('[data-testid="toc-review-edit-0"]').click()
    await page.locator('[data-testid="toc-review-page"]').fill('1')
    await page.locator('[data-testid="toc-review-calibrate"]').click()
    await page.locator('[data-testid="toc-review-delete-1"]').click()
    assert.equal(await page.locator('[data-testid="toc-review-delete-0"]').textContent(), language === 'en' ? 'Delete' : '删除')
    await page.locator('[data-testid="toc-review-ok-0"]').click()
    await page.locator('[data-testid="toc-review-ok-1"]').click()
    await page.locator('[data-testid="toc-review-delete-1"]').click()
    await page.locator('[data-testid="toc-review-delete-0"]').click()
    assert.equal(await page.locator('[data-testid="toc-review-empty"]').isVisible(), true)
    assert.equal(await page.locator('[data-testid="toc-review-save"]').isDisabled(), true)
    await page.locator('[data-testid="toc-review-undo-delete"]').click()
    await page.locator('[data-testid="toc-review-undo-delete"]').click()
    assert.match(await page.locator('[data-testid="toc-review-progress"]').textContent(), /2 \/ 2/)
    await page.locator('[data-testid="toc-review-save"]').click()
    await page.locator('[data-testid="toc-review"]').waitFor({ state: 'hidden' })
    const chapters = await page.evaluate(() => new Promise(resolve => { const request = indexedDB.open('ai-education-reader'); request.onsuccess = () => { const db = request.result, get = db.transaction('documents').objectStore('documents').getAll(); get.onsuccess = () => { resolve(get.result[0].chapters); db.close() } } }))
    assert.equal(chapters.length, 2)
    assert.deepEqual(chapters.map(row => row.title), ['Entry 0', 'Entry 2'])
    assert.deepEqual(errors, [])
    console.log('PASS ' + language + '/' + width + 'px: 942-row usable list, collapsed notes/editor, PDF peek, delete/undo, metadata alignment, empty protection and saved exclusion')
    await context.close()
  }
} finally { await browser.close() }
